"""Generate README.md, categories/*.md and vendors/*.md from data/.

Usage: python scripts/render.py            # write files
       python scripts/render.py --check    # exit 1 if README.md is out of date
"""
from __future__ import annotations

import re
import sys
from datetime import date

from common import ROOT, fmt_num, item_url, load_all

REPO = "The-Web-Scraping-Insider/awesome-web-scraping-mcp-servers"
REPO_URL = f"https://github.com/{REPO}"
SKILLS_URL = "https://github.com/The-Web-Scraping-Insider/awesome-web-scraping-skills"
SUBREDDIT = "https://www.reddit.com/r/WebScrapingInsider/"
SCRAPEOPS = "https://scrapeops.io/?utm_source=awesome-web-scraping-mcp-servers&utm_medium=github"
GENERATED = "<!-- GENERATED by scripts/render.py from data/*.yaml. Do not edit by hand. -->"
HOSTING = {"hosted": "☁️ Hosted", "local": "🏠 Local", "both": "☁️ Hosted · 🏠 Local"}


def publisher(s, vendors):
    return vendors[s["vendor"]]["name"] if s.get("vendor") else f"@{s['author']}"


def publisher_md(s, vendors):
    if s.get("vendor"):
        v = vendors[s["vendor"]]
        return f"[{v['name']}]({v['site']})"
    return f"[@{s['author']}](https://github.com/{s['author']})"


def stats_line(s, caps_by_id):
    bits = []
    if s["stars"] is not None:
        star = f"⭐ {fmt_num(s['stars'])}" + ("†" if s.get("catalog") else "")
        if s.get("stars_week") and s["stars_week"] > 0:
            star += f" (+{s['stars_week']} this week)"
        bits.append(star)
    if s["archived"]:
        bits.append("📦 Archived")
    bits.append(HOSTING[s["hosting"]])
    if not s["paid_api"]:
        bits.append("🆓 Free")
    elif s.get("free_tier"):
        bits.append(f"🔑 Free tier: {s['free_tier']}")
    else:
        bits.append("🔑 API key")
    tags = [caps_by_id[c]["short"] for c in s["capabilities"] if c != "open-source"]
    if tags:
        bits.append(" · ".join(f"`{t}`" for t in tags))
    return " · ".join(bits)


def item(s, vendors, caps_by_id, show_publisher=True):
    by = f" by {publisher_md(s, vendors)}" if show_publisher else ""
    desc = s["description"].rstrip(".") + "."
    return f"- [**{s['name']}**]({item_url(s)}){by} - {desc}<br><sub>{stats_line(s, caps_by_id)}</sub>"


def install_block(servers):
    lines = []
    for s in servers:
        lines.append(f"# {s['name']}")
        if s.get("endpoint"):
            lines.append(f"# remote endpoint: {s['endpoint']}")
        lines.append(s["install"])
    body = "\n".join(lines)
    return f"<details><summary>Install / connect</summary>\n\n```bash\n{body}\n```\n\n</details>"


def anchor(text):
    a = re.sub(r"[^\w\- ]", "", text.strip().lower())
    return a.replace(" ", "-")


def render_readme(servers, vendors, categories, caps, picks, stats):
    caps_by_id = {c["id"]: c for c in caps}
    by_id = {s["id"]: s for s in servers}
    ranked = sorted(servers, key=lambda s: -s["score"])
    official = [s for s in servers if s["type"] != "community"]
    community = [s for s in servers if s["type"] == "community"]
    vendor_ids = sorted({s["vendor"] for s in official})
    updated = stats.get("updated") or date.today().isoformat()
    n_free = sum(1 for s in servers if not s["paid_api"])
    n_hosted = sum(1 for s in servers if s["hosting"] in ("hosted", "both"))

    L = []
    w = L.append
    w(GENERATED)
    w('<div align="center">\n')
    w("# Awesome Web Scraping MCP Servers [![Awesome](https://awesome.re/badge.svg)](https://awesome.re)\n")
    w("**A curated, auto-ranked list of [MCP](https://modelcontextprotocol.io) servers that give Claude, Cursor, ChatGPT and other AI agents live access to web data: scraping, crawling, browsers and search.**\n")
    badges = [
        f"![Servers](https://img.shields.io/badge/servers-{len(servers)}-2563eb)",
        f"![Official](https://img.shields.io/badge/official-{len(official)}-16a34a)",
        f"![Free](https://img.shields.io/badge/free%20%2F%20open%20source-{n_free}-f59e0b)",
        f"![Hosted](https://img.shields.io/badge/hosted%20endpoints-{n_hosted}-8b5cf6)",
        f"![Updated](https://img.shields.io/badge/updated-{updated.replace('-', '--')}-6b7280)",
        f"[![PRs Welcome](https://img.shields.io/badge/PRs-welcome-brightgreen)]({REPO_URL}/blob/main/CONTRIBUTING.md)",
    ]
    w(" ".join(badges) + "\n")
    w(f"<sub>Stars refreshed daily · Curated by <a href=\"{SUBREDDIT}\">The Web Scraping Insider</a> · "
      f"Looking for agent skills instead? See <a href=\"{SKILLS_URL}\">Awesome Web Scraping Skills</a></sub>\n")
    w("</div>\n")

    w("## Contents\n")
    toc = ["What is a scraping MCP server?", "Top 10", "Quick picks", "Official servers",
           "Community servers", "Comparison table", "Browse by category",
           "Related lists", "Contributing", "How the ranking works"]
    for t in toc:
        w(f"- [{t}](#{anchor(t)})")
    w("")

    w("## What is a scraping MCP server?\n")
    w("The [Model Context Protocol](https://modelcontextprotocol.io) lets an AI app call external tools. "
      "A scraping MCP server gives the agent tools like `scrape`, `crawl`, `search` or `browser_click`, "
      "so it can fetch live pages, get past blocks and return clean data inside the conversation.\n")
    w("- **☁️ Hosted** servers run on the vendor's infrastructure: paste a URL into your client, nothing to install.")
    w("- **🏠 Local** servers run on your machine with `npx`, `uvx`, `pip` or Docker.")
    w("- **🆓 Free** means open source and no paid account needed; **🔑** means you need an API key (most offer a free tier).\n")
    w("```bash\n# Claude Code: add a local server\nclaude mcp add <name> -- npx -y <package>\n"
      "# Claude Code: add a hosted server\nclaude mcp add --transport http <name> <endpoint-url>\n```\n")

    w("## Top 10\n")
    w("Ranked by score (GitHub stars and recent activity; see [how the ranking works](#how-the-ranking-works)).\n")
    w("| # | Server | Publisher | Type | Hosting | ⭐ Stars | Score |")
    w("|---:|---|---|---|---|---:|---:|")
    for i, s in enumerate(ranked[:10], 1):
        typ = "Official" if s["type"] != "community" else "Community"
        star = fmt_num(s["stars"]) + ("†" if s.get("catalog") and s["stars"] is not None else "")
        w(f"| {i} | [{s['name']}]({item_url(s)}) | {publisher(s, vendors)} | {typ} | {HOSTING[s['hosting']]} | {star} | {s['score']} |")
    w("\n<sub>† Stars belong to a bigger project that includes the MCP server, so they count for less in the score.</sub>\n")

    w("## Quick picks\n")
    w("| I need to… | Try |")
    w("|---|---|")
    for p in picks:
        links = ", ".join(f"[{by_id[i]['name']}]({item_url(by_id[i])})" for i in p["servers"])
        w(f"| {p['need']} | {links} |")
    w("")

    w("## Official servers\n")
    w("Published by the company or project behind the tool, grouped by category and ordered by score.\n")
    for c in categories:
        cs = sorted([s for s in official if s["category"] == c["id"]], key=lambda s: -s["score"])
        if not cs:
            continue
        w(f"### {c['emoji']} {c['title']}\n")
        for s in cs:
            w(item(s, vendors, caps_by_id))
        w("")
        w(install_block(cs))
        w("")

    w("## Community servers\n")
    w("Built by independent developers, often wrapping an open-source library or someone else's API.\n")
    for c in categories:
        cs = sorted([s for s in community if s["category"] == c["id"]], key=lambda s: -s["score"])
        if not cs:
            continue
        w(f"### {c['emoji']} {c['title']}\n")
        for s in cs:
            w(item(s, vendors, caps_by_id))
        w("")
        w(install_block(cs))
        w("")

    w("## Comparison table\n")
    w("What each server can do, as described in its own documentation. Free tiers are as the vendor states them.\n")
    w("<details><summary>Show the full table</summary>\n")
    cols = [c for c in caps if c["id"] != "open-source"]
    w("| Server | Hosting | Free | " + " | ".join(c["short"] for c in cols) + " |")
    w("|---|---|---|" + "|".join(":-:" for _ in cols) + "|")
    for s in ranked:
        free = "✅" if not s["paid_api"] else (s.get("free_tier") or "")
        cells = ["✅" if c["id"] in s["capabilities"] else "" for c in cols]
        w(f"| [{s['name']}]({item_url(s)}) | {HOSTING[s['hosting']]} | {free} | " + " | ".join(cells) + " |")
    w("\n" + " · ".join(f"**{c['short']}**: {c['description']}" for c in cols) + "\n")
    w("</details>\n")

    w("## Browse by category\n")
    for c in categories:
        n = sum(1 for s in servers if s["category"] == c["id"])
        if n:
            w(f"- [{c['emoji']} {c['title']}](categories/{c['id']}.md) ({n}) - {c['blurb']}")
    w("\nOr by vendor: " + " · ".join(f"[{vendors[v]['name']}](vendors/{v}.md)" for v in vendor_ids) + "\n")

    w("## Related lists\n")
    w(f"- [Awesome Web Scraping Skills]({SKILLS_URL}) - Our companion list of Agent Skills for scraping.")
    w("- [punkpeye/awesome-mcp-servers](https://github.com/punkpeye/awesome-mcp-servers) - The big general list of MCP servers.")
    w("- [modelcontextprotocol/servers](https://github.com/modelcontextprotocol/servers) - Official reference servers and registry.")
    w("- [lorien/awesome-web-scraping](https://github.com/lorien/awesome-web-scraping) - Scraping libraries, tools and APIs.")
    w(f"- [r/WebScrapingInsider]({SUBREDDIT}) - Scraping community, with AMAs from the people who build these tools.")
    w("")

    w("## Contributing\n")
    w(f"Missing a server? [Submit it with the form]({REPO_URL}/issues/new?template=submit-server.yml) "
      "or open a PR that edits [`data/servers.yaml`](data/servers.yaml). Don't edit this README; it's generated. "
      "See [CONTRIBUTING.md](CONTRIBUTING.md).\n")
    w("**Are you listed?** Add the badge to your repo:\n")
    w(f"[![Featured in Awesome Web Scraping MCP Servers](assets/badges/featured.svg)]({REPO_URL})\n")
    w("```markdown\n"
      f"[![Featured in Awesome Web Scraping MCP Servers](https://raw.githubusercontent.com/{REPO}/main/assets/badges/featured.svg)]({REPO_URL})\n"
      "```\n")

    w("## How the ranking works\n")
    w("Each server gets a score from 0 to 100: **85% GitHub stars** (log-scaled) and **15% recent activity** "
      "(commits in the last 90 days). Stars of a bigger project that only includes an MCP server count for a quarter, "
      "and archived repos are halved. Closed-source servers have no stars, so they rank by activity only and are listed "
      "for completeness. Inclusion is editorial; ranking is automatic and identical for every vendor. "
      "Details: [METHODOLOGY.md](METHODOLOGY.md).\n")

    w("---\n")
    w(f'<div align="center"><sub>Curated by <a href="{SUBREDDIT}">The Web Scraping Insider</a> · '
      f'Supported by <a href="{SCRAPEOPS}">ScrapeOps</a> · Stats last refreshed {updated}</sub></div>')
    return "\n".join(L) + "\n"


def render_category(c, servers, vendors, caps):
    caps_by_id = {x["id"]: x for x in caps}
    cs = sorted([s for s in servers if s["category"] == c["id"]], key=lambda s: -s["score"])
    L = [GENERATED, f"# {c['emoji']} {c['title']}\n", f"{c['blurb']}\n", "[← Back to the list](../README.md)\n"]
    for label, group in (("Official", [s for s in cs if s["type"] != "community"]),
                         ("Community", [s for s in cs if s["type"] == "community"])):
        if group:
            L += [f"## {label}\n"] + [item(s, vendors, caps_by_id) for s in group] + ["", install_block(group), ""]
    return "\n".join(L) + "\n"


def render_vendor(vid, servers, vendors, caps, categories):
    caps_by_id = {x["id"]: x for x in caps}
    cat_title = {c["id"]: c["title"] for c in categories}
    v = vendors[vid]
    vs = sorted([s for s in servers if s.get("vendor") == vid], key=lambda s: -s["score"])
    L = [GENERATED, f"# {v['name']} MCP server\n", f"{v['kind']} · [{v['site']}]({v['site']})\n",
         "[← Back to the list](../README.md)\n",
         "| Server | Category | Hosting | ⭐ Stars | Score |", "|---|---|---|---:|---:|"]
    for s in vs:
        L.append(f"| [{s['name']}]({item_url(s)}) | {cat_title[s['category']]} | {HOSTING[s['hosting']]} | {fmt_num(s['stars'])} | {s['score']} |")
    L += [""] + [item(s, vendors, caps_by_id, show_publisher=False) for s in vs] + ["", install_block(vs)]
    return "\n".join(L) + "\n"


def main():
    servers, vendors, categories, caps, picks, stats = load_all()
    readme = render_readme(servers, vendors, categories, caps, picks, stats)
    if "--check" in sys.argv:
        current = (ROOT / "README.md").read_text(encoding="utf-8") if (ROOT / "README.md").exists() else ""
        sys.exit(0 if current == readme else 1)
    (ROOT / "README.md").write_text(readme, encoding="utf-8")
    (ROOT / "categories").mkdir(exist_ok=True)
    for c in categories:
        if any(s["category"] == c["id"] for s in servers):
            (ROOT / "categories" / f"{c['id']}.md").write_text(render_category(c, servers, vendors, caps), encoding="utf-8")
    (ROOT / "vendors").mkdir(exist_ok=True)
    for vid in {s["vendor"] for s in servers if s.get("vendor")}:
        (ROOT / "vendors" / f"{vid}.md").write_text(render_vendor(vid, servers, vendors, caps, categories), encoding="utf-8")
    print(f"Rendered README with {len(servers)} servers.")


if __name__ == "__main__":
    main()
